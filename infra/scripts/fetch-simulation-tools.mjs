import { mkdir, writeFile, rename } from 'node:fs/promises';
import { createWriteStream } from 'node:fs';
import { Readable, Transform } from 'node:stream';
import { pipeline } from 'node:stream/promises';
import { createHash } from 'node:crypto';
const gcc = process.argv[2] === 'gcc';
const url = gcc ? 'https://github.com/xpack-dev-tools/riscv-none-elf-gcc-xpack/releases/download/v15.2.0-1/xpack-riscv-none-elf-gcc-15.2.0-1-win32-x64.zip' : 'https://github.com/YosysHQ/oss-cad-suite-build/releases/download/2026-10-21/oss-cad-suite-windows-x64-20261021.tgz';
const expected = gcc ? '85ef714dacd273b1dadf4af4892774520ac01915bfa6da816a56e7e41591e09e' : 'ac6c0032046d15dc9213b1ee66c30629d4a8f6e98c3bdc1804b69f9c2a83a905';
const target = gcc ? '.tools/downloads/riscv-gcc.zip' : '.tools/downloads/oss-cad-suite.tgz';
await mkdir('.tools/downloads', { recursive: true });
const response = await fetch(url, { signal: AbortSignal.timeout(600000) });
if (!response.ok) throw Error(`HTTP ${response.status}`);
const hash = createHash('sha256'); let bytes = 0, last = 0;
const progress = new Transform({ transform(chunk, _, callback) { hash.update(chunk); bytes += chunk.length; if (bytes-last > 50_000_000) { console.log(`Downloaded ${Math.round(bytes/1e6)} MB`); last = bytes; } callback(null, chunk); } });
await pipeline(Readable.fromWeb(response.body), progress, createWriteStream(`${target}.part`));
const actual = hash.digest('hex');
if (actual !== expected) throw Error(`SHA256 mismatch: ${actual}`);
await rename(`${target}.part`, target);
await mkdir('docs/test-evidence/real-soc', { recursive: true });
await writeFile(`docs/test-evidence/real-soc/${gcc ? 'gcc' : 'toolchain'}-download.json`, JSON.stringify({ url, release: gcc ? 'v15.2.0-1' : '2026-10-21', sha256: actual, bytes, expected_hash_source: 'GitHub release asset digest', scope: 'External portable tools for feasibility only; no redistribution/license clearance implied' }, null, 2)+'\n');
console.log('Download hash verified');
